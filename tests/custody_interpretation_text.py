"""Regenerate the CPython 3.11 Unicode 14 repr printability table."""
from pathlib import Path
import sys
import unicodedata

PATH = Path(__file__).resolve().parents[1] / "crates/custody/src/interpretation/printable.rs"


def source():
    assert sys.version_info[:2] == (3, 11) and unicodedata.unidata_version == "14.0.0"
    ranges = []
    start = None
    for point in range(0x110001):
        unprintable = point < 0x110000 and not chr(point).isprintable()
        if unprintable and start is None:
            start = point
        elif not unprintable and start is not None:
            ranges.append((start, point - 1))
            start = None
    return "// Generated by tests/custody_interpretation_text.py (CPython 3.11).\nconst NONPRINTABLE: &[(u32, u32)] = &[\n" + "".join(f"    (0x{a:x}, 0x{b:x}),\n" for a, b in ranges) + "];\n"


if __name__ == "__main__":
    if "--write" in sys.argv:
        PATH.write_text(source())
    else:
        assert PATH.read_text() == source()
