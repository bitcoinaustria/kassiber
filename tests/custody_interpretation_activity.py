def assert_scenario_activity(counts, name, scenarios, size=2000):
    expected = EXPECTED_ACTIVITY[name]
    assert set(expected) == set(scenarios)
    for index, case in enumerate(scenarios):
        expected_count = size // len(scenarios) + (index < size % len(scenarios))
        for state in ("active", "blocked", "inactive"):
            # Samourai's duplicated target aliases a canonical observation.
            # Sat rounding changes which candidate exhausts its source first.
            if name == "samourai" and case == "duplicate_target":
                expected_state_count = {"active": 0, "blocked": 37, "inactive": 21}[state]
            else:
                expected_state_count = expected_count if expected[case] == state else 0
            assert counts[f"scenario:{case}:{state}"] == expected_state_count, (name, case, state, dict(counts))
