"""Write src/unicode_tables.rs from this interpreter's unicodedata.

The tables pin what CPython 3.11 (Unicode 14.0.0) answers for
`str.isspace`, `str.isprintable`, `str.isalnum`, `unicodedata.decimal`,
and SRE IGNORECASE, which decide text parsing and redaction. Run with the
locked 3.11 interpreter:

    .venv/bin/python crates/pytext/scripts/gen_unicode_tables.py
    .venv/bin/python crates/pytext/scripts/gen_unicode_tables.py --check
"""

from __future__ import annotations

import _sre
import argparse
import sys
import unicodedata
from pathlib import Path
from re._casefix import _EXTRA_CASES

TARGET = Path(__file__).resolve().parents[1] / "src" / "unicode_tables.rs"


def ranges(predicate) -> list[tuple[int, int]]:
    result: list[tuple[int, int]] = []
    start = None
    for point in range(0x110000):
        if predicate(point):
            if start is None:
                start = point
        elif start is not None:
            result.append((start, point - 1))
            start = None
    if start is not None:
        result.append((start, 0x10FFFF))
    return result


def table(name: str, doc: str, items: list[tuple[int, int]]) -> str:
    lines = [f"/// {doc}", f"pub(crate) const {name}: &[(u32, u32)] = &["]
    row: list[str] = []
    for start, end in items:
        row.append(f"(0x{start:X}, 0x{end:X})")
        if len(row) == 4:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    return "\n".join(lines)


def render() -> str:
    if sys.version_info[:2] != (3, 11) or unicodedata.unidata_version != "14.0.0":
        raise SystemExit("run with the locked Python 3.11 interpreter (Unicode 14.0.0)")
    spaces = ranges(lambda c: chr(c).isspace())
    alphabetic = ranges(lambda c: chr(c).isalpha())
    not_printable = ranges(lambda c: not chr(c).isprintable())
    decimals = ranges(lambda c: unicodedata.decimal(chr(c), None) is not None)
    words = ranges(lambda c: chr(c).isalnum() or c == ord("_"))
    # SRE lowers each character, then also accepts its compiler's extra
    # equivalences (not str.casefold, which can expand to several characters).
    ascii_cases = []
    for letter in range(ord("a"), ord("z") + 1):
        equivalents = {letter, *_EXTRA_CASES.get(letter, ())}
        ascii_cases.append([c for c in range(0x110000) if _sre.unicode_tolower(c) in equivalents])

    def regex_class(items):
        return "[" + "".join(
            rf"\x{{{start:x}}}" + (rf"-\x{{{end:x}}}" if start != end else "")
            for start, end in items
        ) + "]"
    for start, end in decimals:
        # Every run starts at a zero and holds whole decades, so a digit's
        # value is its offset from the run start modulo ten.
        assert unicodedata.decimal(chr(start)) == 0, hex(start)
        assert (end - start + 1) % 10 == 0, hex(start)
        for point in range(start, end + 1):
            assert unicodedata.decimal(chr(point)) == (point - start) % 10
    parts = [
        "// @generated by crates/pytext/scripts/gen_unicode_tables.py from",
        # The minor version only: CPython keeps a release line's Unicode data
        # and these predicates fixed across its patch releases, so a CI
        # runner on another 3.11.x must reproduce the file byte for byte.
        f"// CPython {sys.version_info[0]}.{sys.version_info[1]}, Unicode {unicodedata.unidata_version}."
        " Do not edit by hand.",
        "",
        f'pub(crate) const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        table("SPACE", "Code points where `str.isspace()` is true.", spaces),
        "",
        table("ALPHA", "Code points where `str.isalpha()` is true.", alphabetic),
        "",
        table(
            "NOT_PRINTABLE",
            "Code points where `str.isprintable()` is false; `repr` escapes them.",
            not_printable,
        ),
        "",
        table(
            "DECIMAL_RUNS",
            "Runs of `unicodedata.decimal` digits; each starts at a zero.",
            decimals,
        ),
        "",
        "/// CPython str-pattern character classes, without regex-engine Unicode tables.",
        f'pub const REGEX_WORD: &str = r"{regex_class(words)}";',
        f'pub const REGEX_SPACE: &str = r"{regex_class(spaces)}";',
        f'pub const REGEX_DIGIT: &str = r"{regex_class(decimals)}";',
        "",
        "/// SRE IGNORECASE equivalences for ASCII a-z, as class interiors.",
        "pub const REGEX_ASCII_CASES: &[&str] = &[",
        *[f'    r"{regex_class([(c, c) for c in points])[1:-1]}",' for points in ascii_cases],
        "];",
        "",
    ]
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    text = render()
    if options.check:
        if TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET} is stale; rerun this script", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
