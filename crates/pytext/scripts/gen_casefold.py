#!/usr/bin/env python3
"""Freeze CPython 3.11 / Unicode 14 full case folding for stable identities."""
import sys
import unicodedata
from pathlib import Path
assert sys.version_info[:2]==(3,11)
assert unicodedata.unidata_version=='14.0.0'
root=Path(__file__).resolve().parents[1]
entries=[(n,chr(n).casefold()) for n in range(0x110000) if chr(n).casefold()!=chr(n)]
code='//! Generated by scripts/gen_casefold.py with CPython 3.11 / Unicode 14.\n'
code+='pub fn casefold(text: &str) -> String {\n    let mut out=String::new();\n    for c in text.chars() {\n        match c as u32 {\n'
for n,s in entries:
    escaped=''.join('\\u{'+format(ord(c),'x')+'}' for c in s)
    if len(s)==1:
        code+=f"            0x{n:x} => out.push('{escaped}'),\n"
    else:
        code+=f'            0x{n:x} => out.push_str("{escaped}"),\n'
code+='            _ => out.push(c),\n        }\n    }\n    out\n}\n'
(root/'src/casefold.rs').write_text(code)
(root/'tests/data/casefold.txt').write_text(''.join(f'{n:x};'+','.join(f'{ord(c):x}' for c in s)+'\n' for n,s in entries))
