// Emits Rune `Icon` statics from lucide-react 0.469.0 (the version src/icons.rs was generated from).
// Usage: npm pack lucide-react@0.469.0 && tar -xzf lucide-react-0.469.0.tgz (in a scratch dir), then
//   node tools/lucide-icons.mjs <scratch>/package house wallet ... > src/icons.rs
import { readFileSync } from "node:fs";
import { join } from "node:path";

const [modules, ...names] = process.argv.slice(2);
const attr = (k, v) => `${k.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase())}="${v}"`;
let out = "//! Lucide icons (ISC), generated by tools/lucide-icons.mjs from lucide-react 0.469.0.\n";
out += "#![allow(dead_code)]\nuse rune::Icon;\n\n";
for (const name of names) {
  const src = readFileSync(join(modules, "dist/esm/icons", `${name}.js`), "utf8");
  const body = src.slice(src.indexOf("createLucideIcon("));
  const nodeSrc = body.slice(body.indexOf("["), body.lastIndexOf("]") + 1);
  const nodes = Function(`return ${nodeSrc}`)();
  const svg = nodes
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => attr(k, v)).join(" ");
      return `<${tag} ${a} fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>`;
    })
    .join("");
  const ident = name.toUpperCase().replace(/-/g, "_");
  out += `pub static ${ident}: Icon = Icon { name: "lucide-${name}", view: 24.0, body: r##"${svg}"## };\n`;
}
process.stdout.write(out);
