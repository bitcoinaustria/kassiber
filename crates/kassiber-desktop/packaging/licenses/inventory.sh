#!/usr/bin/env bash
# Third-party inventory of the Rune desktop's Cargo.lock, from local data only (never the
# network): `cargo metadata --offline` for the host platform, then the registry's unpacked
# sources and cached .crate files, then Rune's git checkout for its patched forks.
#
# Usage: packaging/licenses/inventory.sh > inventory.md
# Output: one Markdown table row per locked package (name, version, license, source, flags)
# plus a summary of license expressions and every flagged row. Flags:
#   GIT          a git dependency (not crates.io): pinned by revision, not by checksum
#   UNKNOWN      no license expression found locally (or only `license-file`)
#   COPYLEFT     GPL/LGPL/AGPL/MPL/EPL/CDDL/EUPL/OSL in the expression (review: weak copyleft
#                such as MPL-2.0 is usually fine for unmodified redistribution, GPL is not)
#   NOT-CACHED   the package is not in the local registry (a platform this machine never built)
set -euo pipefail
here="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$here"
cargo_home="${CARGO_HOME:-$HOME/.cargo}"
meta="$(mktemp)"; trap 'rm -f "$meta"' EXIT
host="$(rustc -vV | sed -n 's/^host: //p')"
cargo metadata --format-version 1 --offline --locked --filter-platform "$host" > "$meta"

license_of() { # name version source
  local name="$1" version="$2" source="$3" lic
  lic="$(jq -r --arg n "$name" --arg v "$version" '.packages[] | select(.name==$n and .version==$v) | (.license // (if .license_file then "license-file:" + .license_file else empty end))' "$meta" | head -n1)"
  if [ -n "$lic" ]; then printf '%s|%s' "$lic" "meta"; return; fi
  local toml=""
  case "$source" in
    registry+*)
      for d in "$cargo_home"/registry/src/*/"$name-$version"; do [ -f "$d/Cargo.toml" ] && toml="$d/Cargo.toml" && break; done
      if [ -z "$toml" ]; then
        for c in "$cargo_home"/registry/cache/*/"$name-$version.crate"; do
          if [ -f "$c" ]; then
            lic="$(tar -xOzf "$c" "$name-$version/Cargo.toml" 2>/dev/null | sed -n 's/^license *= *"\(.*\)"/\1/p' | head -n1)"
            [ -n "$lic" ] && { printf '%s|%s' "$lic" "cache"; return; }
          fi
        done
      fi ;;
    git+*)
      local rev="${source##*#}"
      for d in "$cargo_home"/git/checkouts/*/"${rev:0:7}"; do
        [ -d "$d" ] || continue
        toml="$(grep -rl --include=Cargo.toml -E "^name *= *\"$name\"" "$d" 2>/dev/null | head -n1 || true)"
        [ -n "$toml" ] && break
      done ;;
  esac
  if [ -n "$toml" ]; then
    lic="$(sed -n 's/^license *= *"\(.*\)"/\1/p' "$toml" | head -n1)"
    if [ -z "$lic" ] && grep -q '^license.workspace *= *true\|^license = { *workspace' "$toml"; then
      local ws; ws="$(dirname "$toml")"
      while [ "$ws" != "/" ]; do ws="$(dirname "$ws")"; if grep -q '^\[workspace.package\]' "$ws/Cargo.toml" 2>/dev/null; then lic="$(sed -n '/^\[workspace.package\]/,/^\[/s/^license *= *"\(.*\)"/\1/p' "$ws/Cargo.toml" | head -n1)"; break; fi; done
    fi
    [ -n "$lic" ] && { printf '%s|%s' "$lic" "source"; return; }
    printf '%s|%s' "" "source"; return
  fi
  printf '%s|%s' "" "missing"
}

rows="$(mktemp)"; trap 'rm -f "$meta" "$rows"' EXIT
awk '
  /^\[\[package\]\]/ { if (n) print n "\t" v "\t" s; n=""; v=""; s="local" }
  /^name = /    { gsub(/"/, "", $3); n=$3 }
  /^version = / { gsub(/"/, "", $3); v=$3 }
  /^source = /  { gsub(/"/, "", $3); s=$3 }
  END { if (n) print n "\t" v "\t" s }
' Cargo.lock | sort -f > "$rows.lock"
while IFS=$'\t' read -r name version source; do
  IFS='|' read -r lic how < <(license_of "$name" "$version" "$source"; echo)
  flags=()
  case "$source" in git+*) flags+=(GIT) ;; esac
  [ "$source" = local ] && { lic="${lic:-MIT}"; }
  if [ -z "$lic" ] || [[ "$lic" == license-file:* ]]; then flags+=(UNKNOWN); fi
  [ "$how" = missing ] && flags+=(NOT-CACHED)
  if printf '%s' "$lic" | grep -Eq '(^|[^A-Za-z])(A?GPL|LGPL|MPL|EPL|CDDL|EUPL|OSL)'; then flags+=(COPYLEFT); fi
  src="crates.io"; case "$source" in git+*) src="${source#git+}" ;; local) src="this crate" ;; esac
  printf '%s\t%s\t%s\t%s\t%s\n' "$name" "$version" "${lic:-?}" "$src" "${flags[*]:-}" >> "$rows"
done < "$rows.lock"
rm -f "$rows.lock"

total="$(wc -l < "$rows" | tr -d ' ')"
echo "# Rune desktop: locked Rust packages"
echo
echo "Generated by \`packaging/licenses/inventory.sh\` from \`crates/kassiber-desktop/Cargo.lock\` with local data only"
echo "(host \`$host\`): $total packages. Flags: GIT (git dependency), UNKNOWN (no SPDX expression found),"
echo "COPYLEFT (review), NOT-CACHED (never fetched on this machine; licence read in CI)."
echo
echo "## License expressions"
echo
echo "| Expression | Packages |"
echo "| --- | ---: |"
cut -f3 "$rows" | sort | uniq -c | sort -rn | awk '{c=$1; $1=""; sub(/^ /,""); printf "| %s | %d |\n", $0, c}'
echo
echo "## Flagged"
echo
echo "| Package | Version | License | Source | Flags |"
echo "| --- | --- | --- | --- | --- |"
awk -F'\t' '$5 != "" { printf "| `%s` | %s | %s | %s | %s |\n", $1, $2, $3, $4, $5 }' "$rows"
echo
echo "## All packages"
echo
echo "| Package | Version | License | Source | Flags |"
echo "| --- | --- | --- | --- | --- |"
awk -F'\t' '{ printf "| `%s` | %s | %s | %s | %s |\n", $1, $2, $3, $4, $5 }' "$rows"
