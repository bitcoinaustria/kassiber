HEADER = f"""\
# CPython json.dumps and float repr vectors for the kassiber-pyjson crate.
# Generated by crates/pyjson/scripts/gen_json_vectors.py (seed @SEED@); do not edit.
# Python {sys.version.split()[0]}, json {json.__version__}, float_repr_style {sys.float_repr_style},
# int_max_str_digits {sys.get_int_max_str_digits()}.
#
# One case per line, fields separated by tabs; '#' starts a comment.
# Text fields escape the backslash as \\\\ and every other character
# outside printable ASCII as \\u{{<hex>}}; tokens escape the space too.
#
#   float <bits> <repr>             repr(x) for the float with these IEEE
#                                   754 bits (16 hex digits)
#   dumps <options> <input> <out>   json.dumps(input, **options)
#
# <options> is '-' or space-separated flags for the arguments that differ
# from Python's defaults: ascii=0 (ensure_ascii=False), nan=0
# (allow_nan=False), sort (sort_keys=True), indent=<n> or indent=s<text>,
# compact (separators=(',', ':')) or item=s<text> key=s<text>, and str
# (default=str).
#
# <input> is space-separated tokens: N (None), T (True), F (False),
# i<int>, f<16 hex digits> (a float's bits), s<text> (a str, which may hold
# surrogates), d<digits>E<exp> (a Decimal: [-]coefficient and exponent),
# '[' items ']', and '{{' key value ... '}}'. Keys use N, T, F, i, f, and s.
#
# <out> is the result, or '!' and the error kind json.dumps raises:
# OutOfRangeFloat, NotSerializable, UnorderableKeys, IntTooLarge, or
# Surrogate (the result holds a surrogate, which UTF-8 cannot encode).
"""


def escape(text: str, *, space: bool) -> str:
    out = []
    for ch in text:
        point = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif 0x21 <= point <= 0x7E or (point == 0x20 and not space):
            out.append(ch)
        else:
            out.append(f"\\u{{{point:x}}}")
    return "".join(out)


def float_bits(x: float) -> str:
    return f"{struct.unpack('<Q', struct.pack('<d', x))[0]:016x}"


def from_bits(bits: int) -> float:
    return struct.unpack("<d", struct.pack("<Q", bits))[0]


def int_text(n: int) -> str:
    """str(n) past the conversion limit, which json.dumps keeps."""
    limit = sys.get_int_max_str_digits()
    sys.set_int_max_str_digits(0)
    try:
        return str(n)
    finally:
        sys.set_int_max_str_digits(limit)


def token(obj: Any) -> str:
    if obj is None:
        return "N"
    if obj is True:
        return "T"
    if obj is False:
        return "F"
    if isinstance(obj, int):
        return f"i{int_text(obj)}"
    if isinstance(obj, float):
        return f"f{float_bits(obj)}"
    if isinstance(obj, str):
        return f"s{escape(obj, space=True)}"
    if isinstance(obj, Decimal):
        sign, digits, exponent = obj.as_tuple()
        return f"d{'-' if sign else ''}{''.join(map(str, digits))}E{exponent}"
    if isinstance(obj, (list, tuple)):
        return " ".join(["[", *map(token, obj), "]"])
    if isinstance(obj, dict):
        return " ".join(["{", *(f"{token(k)} {token(v)}" for k, v in obj.items()), "}"])
    raise TypeError(f"no token for {type(obj).__name__}")


def options_text(kwargs: dict) -> str:
    parts = []
    if kwargs.get("ensure_ascii") is False:
        parts.append("ascii=0")
    if kwargs.get("allow_nan") is False:
        parts.append("nan=0")
    if kwargs.get("sort_keys"):
        parts.append("sort")
    indent = kwargs.get("indent")
    if isinstance(indent, int):
        parts.append(f"indent={indent}")
    elif isinstance(indent, str):
        parts.append(f"indent=s{escape(indent, space=True)}")
    separators = kwargs.get("separators")
    if separators == COMPACT:
        parts.append("compact")
    elif separators is not None:
        parts.append(f"item=s{escape(separators[0], space=True)}")
        parts.append(f"key=s{escape(separators[1], space=True)}")
    if kwargs.get("default") is str:
        parts.append("str")
    return " ".join(parts) or "-"


def expected(obj: Any, kwargs: dict) -> str:
    try:
        out = json.dumps(obj, **kwargs)
    except ValueError as exc:
        if str(exc).startswith("Out of range float values are not JSON compliant"):
            return "!OutOfRangeFloat"
        if str(exc).startswith("Exceeds the limit"):
            return "!IntTooLarge"
        raise
    except TypeError as exc:
        if "is not JSON serializable" in str(exc):
            return "!NotSerializable"
        if "'<' not supported between instances of" in str(exc):
            return "!UnorderableKeys"
        raise
    try:
        out.encode("utf-8")
    except UnicodeEncodeError:
        return "!Surrogate"
    return escape(out, space=False)


def nan_key_under_sort(obj: Any) -> bool:
    """A dict json.dumps would sort with an inconsistent comparison; the
    crate refuses it (Error::NanKeyOrder), so the vectors leave it out."""
    if isinstance(obj, dict):
        if len(obj) > 1 and any(isinstance(k, float) and k != k for k in obj):
            return True
        return any(nan_key_under_sort(v) for v in obj.values())
    if isinstance(obj, list):
        return any(nan_key_under_sort(v) for v in obj)
    return False


class Vectors:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def float(self, x: float) -> None:
        self.lines.append(f"float\t{float_bits(x)}\t{x!r}")

    def dumps(self, obj: Any, kwargs: dict) -> None:
        if kwargs.get("sort_keys") and nan_key_under_sort(obj):
            raise ValueError("a NaN key under sort_keys has no vector")
        self.lines.append(f"dumps\t{options_text(kwargs)}\t{token(obj)}\t{expected(obj, kwargs)}")


def count(n: int) -> int:
    return max(1, round(n * SCALE))


# Characters by kind, for strings.
ASCII_WORDS = ["", "a", "BTC", "wallet", "Kassiber", "msat", "0", "-1", "a b", "x/y", "{}", "[]", "null"]
SPECIAL = ['"', "\\", "/", "\b", "\f", "\n", "\r", "\t", "\x00", "\x01", "\x1f", " ", "\x7f"]
BMP = (
    [chr(c) for c in range(0x80, 0x100)]
    + list("äöüßÄÖÜ€£¥αβγΩжЯ中文日本語한국어עבריתالعربية")
    + ["́", "​", "‍", "‎", " ", " ", "⁦", "﻿", "�", "￾", "￿"]
)
ASTRAL = ["\U0001f600", "\U0001f4b0", "\U0001d400", "\U00020000", "\U0001f1e6\U0001f1f9", "\U000e0001", "\U0010ffff", "\U00010000"]
SURROGATES = ["\ud800", "\udbff", "\udc00", "\udfff", "\ud83d", "\ude00", "😀"]


class Generator:
    def __init__(self, rng: random.Random) -> None:
        self.rng = rng
        self.decimals = False
        self.nonfinite = False
        self.surrogates = False

    def string(self) -> str:
        rng = self.rng
        if rng.random() < 0.4:
            return rng.choice(ASCII_WORDS)
        pools = [(SPECIAL, 2), (BMP, 3), (ASTRAL, 1), ([chr(c) for c in range(0x21, 0x7F)], 6)]
        if self.surrogates:
            pools.append((SURROGATES, 1))
        chars = []
        for _ in range(rng.randint(1, 10)):
            pool = rng.choices([p for p, _ in pools], weights=[w for _, w in pools])[0]
            chars.append(rng.choice(pool))
        return "".join(chars)

    def int(self) -> int:
        rng = self.rng
        kind = rng.random()
        if kind < 0.4:
            return rng.randint(-1000, 1000)
        if kind < 0.7:
            return rng.randint(0, 21_000_000 * 100_000_000_000)
        if kind < 0.9:
            base = rng.choice([2**31, 2**32, 2**53, 2**63, 2**64, 10**15, 10**18])
            return rng.choice([1, -1]) * (base + rng.randint(-1, 1))
        return rng.choice([1, -1]) * rng.randint(0, 10 ** rng.randint(20, 80))

    def float(self) -> float:
        rng = self.rng
        kind = rng.random()
        if self.nonfinite and kind < 0.06:
            return rng.choice([float("nan"), float("inf"), float("-inf"), -float("nan")])
        if kind < 0.35:
            return round(rng.uniform(-100_000, 100_000), rng.randint(0, 8))
        if kind < 0.5:
            return rng.choice([0.0, -0.0, 1.0, 0.1, 0.5, 1e16, 1e15, 1e-4, 1e-5, 5e-324, 1.7976931348623157e308])
        if kind < 0.7:
            return rng.randint(-(10**17), 10**17) / 10 ** rng.randint(0, 20)
        while True:
            x = from_bits(rng.getrandbits(64))
            if x == x and abs(x) != float("inf"):
                return x

    def decimal(self) -> Decimal:
        rng = self.rng
        if rng.random() < 0.3:
            return Decimal(rng.choice(["0", "-0", "0E-8", "1E+3", "-0.000001", "1E-7", "123.4500", "0.00000001", "21000000", "-1.5E+300"]))
        digits = str(rng.randint(0, 10 ** rng.randint(1, 34)))
        exponent = rng.randint(-40, 30)
        return Decimal(f"{rng.choice(['', '-'])}{digits}E{exponent}")

    def scalar(self) -> Any:
        rng = self.rng
        kinds = ["str", "int", "float", "none", "bool"]
        weights = [5, 3, 3, 1, 1]
        if self.decimals:
            kinds.append("decimal")
            weights.append(1)
        kind = rng.choices(kinds, weights=weights)[0]
        return {
            "str": self.string,
            "int": self.int,
            "float": self.float,
            "none": lambda: None,
            "bool": lambda: rng.random() < 0.5,
            "decimal": self.decimal,
        }[kind]()

    def keys(self, n: int) -> list:
        rng = self.rng
        kind = rng.choices(["str", "int", "numeric", "mixed", "special"], weights=[82, 8, 4, 4, 2])[0]
        if kind == "str":
            return [self.string() for _ in range(n)]
        if kind == "int":
            return [self.int() for _ in range(n)]
        if kind == "numeric":
            return [rng.choice([self.int, self.float, lambda: rng.random() < 0.5])() for _ in range(n)]
        if kind == "mixed":
            return [rng.choice([self.string, self.int, lambda: None])() for _ in range(n)]
        return [rng.choice([None, True, False, self.float(), self.int()]) for _ in range(n)]

    def value(self, depth: int) -> Any:
        rng = self.rng
        if depth < 4 and rng.random() < 0.45 / (depth + 1):
            n = rng.randint(0, 6)
            if rng.random() < 0.4:
                return [self.value(depth + 1) for _ in range(n)]
            return {k: self.value(depth + 1) for k in self.keys(n)}
        return self.scalar()

    def document(self) -> Any:
        rng = self.rng
        self.decimals = rng.random() < 0.3
        self.nonfinite = rng.random() < 0.2
        self.surrogates = rng.random() < 0.1
        shape = rng.random()
        if shape < 0.7:
            return {k: self.value(1) for k in self.keys(rng.randint(0, 7))}
        if shape < 0.9:
            return [self.value(1) for _ in range(rng.randint(0, 7))]
        return self.scalar()

    def kassiber_shape(self) -> Any:
        """Payload shapes like the hashed and stored ones in kassiber/."""
        rng = self.rng

        def uuid() -> str:
            return "%08x-%04x-4%03x-%04x-%012x" % (
                rng.getrandbits(32), rng.getrandbits(16), rng.getrandbits(12),
                0x8000 | rng.getrandbits(14), rng.getrandbits(48),
            )

        def txid() -> str:
            return "%064x" % rng.getrandbits(256)

        def timestamp() -> str:
            return f"20{rng.randint(17, 26)}-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}T{rng.randint(0, 23):02d}:{rng.randint(0, 59):02d}:{rng.randint(0, 59):02d}Z"

        kind = rng.randrange(5)
        if kind == 0:  # canonical_observed_quantity_hash
            return {
                "schema_version": 1,
                "wallet_id": uuid(),
                "external_id": txid(),
                "direction": rng.choice(["inbound", "outbound"]),
                "asset": rng.choice(["BTC", "LBTC"]),
                "amount_msat": self.int(),
                "fee_msat": rng.randint(0, 10**9),
                "amount_includes_fee": rng.random() < 0.5,
            }
        if kind == 1:  # custody_quantity_runtime._issue_id parts
            return [str(part) for part in (uuid(), timestamp(), txid(), rng.randint(0, 10**12), self.string())]
        if kind == 2:  # graph and provenance payloads
            return {
                "txid": txid(),
                "vin": [{"txid": txid(), "vout": rng.randint(0, 20), "value": self.float()} for _ in range(rng.randint(0, 3))],
                "vout": [{"n": n, "value": self.float(), "address": self.string()} for n in range(rng.randint(0, 3))],
                "fee": self.decimal() if self.decimals else self.float(),
                "label": self.string(),
                "confirmed_at": timestamp(),
            }
        if kind == 3:  # gap candidate fingerprints
            return {
                "schema_version": 1,
                "gap_id": uuid(),
                "source_ids": sorted(uuid() for _ in range(rng.randint(0, 3))),
                "source_total_msat": self.int(),
                "competitor_score_margin": self.float(),
                "reason_codes": [rng.choice(["amount_match", "time_window", "fee_fit"]) for _ in range(rng.randint(0, 3))],
                "started_at": timestamp(),
                "ended_at": None if rng.random() < 0.3 else timestamp(),
            }
        return {  # a machine envelope row, Decimals already floats
            "kind": "reports.summary",
            "schema_version": 1,
            "data": [{"wallet": self.string(), "balance": self.float(), "rows": rng.randint(0, 10**6)} for _ in range(rng.randint(0, 3))],
        }


def floats(vectors: Vectors, rng: random.Random) -> None:
    for x in (0.0, -0.0, float("inf"), float("-inf"), float("nan"), -float("nan"), 1.0, 0.1, 1 / 3):
        vectors.float(x)
    for bits in (1, 2, 0x000F_FFFF_FFFF_FFFF, 0x0010_0000_0000_0000, 0x7FEF_FFFF_FFFF_FFFF, 0x7FF8_0000_0000_0001):
        vectors.float(from_bits(bits))
    # Powers of two and ten, and their neighbours.
    for exponent in range(-1074, 1024, max(1, round(4 / SCALE))):
        bits = struct.unpack("<Q", struct.pack("<d", 2.0**exponent))[0]
        for delta in (-1, 0, 1):
            if 0 < bits + delta < 0x7FF0_0000_0000_0000:
                vectors.float(from_bits(bits + delta))
    for exponent in range(-325, 309):
        x = float(f"1e{exponent}")
        if 0 < x < float("inf"):
            bits = struct.unpack("<Q", struct.pack("<d", x))[0]
            for delta in (-1, 0, 1):
                vectors.float(from_bits(bits + delta))
    # The layout boundaries: 16 integer digits, and 1e-4 against 1e-5.
    for text in ("9999999999999998.0", "9999999999999999.0", "1e16", "1e15", "999999999999999.9", "0.0001", "0.00009999999999999999", "0.00001", "123456789012345678", "1234567890123456.7"):
        vectors.float(float(text))
    # Exact ties between two shortest candidates: CPython keeps the even digit.
    ties = 0
    while ties < count(2500):
        n = rng.randint(1, 17)
        coefficient = rng.randint(10 ** (n - 1), 10**n - 1)
        exponent = rng.randint(-30, 25)
        exact = Fraction(2 * coefficient + 1, 2) * Fraction(10) ** exponent
        try:
            x = float(exact)
        except OverflowError:
            continue
        if Fraction(x) == exact:
            vectors.float(rng.choice([x, -x]))
            ties += 1
    for _ in range(count(5000)):
        x = from_bits(rng.getrandbits(64))
        vectors.float(x)
    for _ in range(count(2500)):
        vectors.float(round(rng.uniform(-1e6, 1e6), rng.randint(0, 8)))
        vectors.float(rng.randint(-(10**17), 10**17) / 10 ** rng.randint(0, 20))
    for _ in range(count(1000)):
        mantissa = rng.randint(2**52, 2**53 - 1)
        vectors.float(mantissa * 2.0 ** rng.randint(-60, 12))


def strings(vectors: Vectors) -> None:
    chars = [chr(c) for c in range(0x80)] + [
        "\x80", "\x9f", "\xa0", "\xe9", "\xff", "Ā", "߿", "ࠀ", " ", " ",
        "퟿", "\ud800", "\udbff", "\udc00", "\udfff", "", "﻿", "�", "￾", "￿",
        "\U00010000", "\U0001f600", "\U0010ffff",
    ]
    texts = chars + [
        "😀",  # two surrogate code points, not one astral character
        "\ud83d" + "a",
        "a\udc00",
        "\udc00\ud800",
        "caf\xe9 \U0001f600 \"q\" \\ \n",
        "",
    ]
    for ascii_only in (True, False):
        kwargs = {} if ascii_only else {"ensure_ascii": False}
        for text in texts:
            vectors.dumps(text, kwargs)
        for text in texts[0x20:0x80:3] + texts[0x80:]:
            vectors.dumps({text: text}, {**kwargs, "sort_keys": True})
    # Code point order under sort_keys, surrogates included.
    keys = ["퟿", "\ud800", "", "￿", "\U0001f600", "😀", "a", "B", "", "\x00"]
    for ascii_only in (True, False):
        vectors.dumps({k: i for i, k in enumerate(keys)}, {"sort_keys": True, "ensure_ascii": ascii_only})


def ints(vectors: Vectors) -> None:
    values = [0, 1, -1, 2**31, -(2**31), 2**53 + 1, 2**63 - 1, -(2**63), 2**64, -(2**64) - 1, 10**30, -(10**40) + 7]
    limit = sys.get_int_max_str_digits()
    values += [10 ** (limit - 1), -(10 ** (limit - 1)), 10**limit - 1, 10**limit, -(10**limit), 10 ** (limit + 50)]
    for n in values:
        vectors.dumps(n, {})
        vectors.dumps([n, "after"], {"separators": COMPACT})
        vectors.dumps({n: n}, {"sort_keys": True})
    vectors.dumps({10**limit: 1, "a": float("nan")}, {"allow_nan": False})
    vectors.dumps({"a": float("nan"), 10**limit: 1}, {"allow_nan": False})


def specials(vectors: Vectors) -> None:
    nan, inf = float("nan"), float("inf")
    for allow in (True, False):
        kwargs = {} if allow else {"allow_nan": False}
        for x in (nan, -nan, inf, -inf, -0.0, 1e16, 1e-5):
            vectors.dumps(x, kwargs)
            vectors.dumps([1, x], kwargs)
            vectors.dumps({x: 1}, kwargs)


def keys(vectors: Vectors) -> None:
    nan, inf = float("nan"), float("inf")
    cases = [
        {1: "a"}, {True: 1}, {False: 1}, {None: 1}, {1.5: 1}, {-0.0: 1}, {inf: 1}, {-inf: 1}, {nan: 1},
        {1e16: 1}, {1e-5: 1}, {2**70: 1},
        {"b": 1, "a": 2, "B": 3, "": 4},
        {2: "a", 10: "b", 1.5: "c", True: "d", -0.0: "e", -inf: "f", inf: "g"},
        {2**53 + 1: "int", 2.0**53: "float", 2**53 - 1: "below"},
        {-(2**64): 1, -1.5e19: 2, 5e-324: 3, 0: 4},
        {False: 0, 0.5: 1},
        {"a": 1, 1: 2},
        {1: 1, "a": 2},
        {None: 1, "a": 2},
        {None: 1, 0: 2},
        {"a": {1: 2, "b": 3}},
        {1: "a", "1": "b", 1.5: "c", "1.5": "d"},
    ]
    option_sets = [{}, {"sort_keys": True}, {"sort_keys": True, "allow_nan": False}, {"separators": COMPACT, "sort_keys": True}, {"indent": 2, "sort_keys": True}]
    for case in cases:
        for kwargs in option_sets:
            if kwargs.get("sort_keys") and nan_key_under_sort(case):
                continue
            vectors.dumps(case, kwargs)


def decimals(vectors: Vectors, gen: Generator) -> None:
    texts = ["0", "-0", "0.0", "0E-8", "-0E+3", "1", "1.0", "1E+3", "1E+5", "-0.000001", "0.0000001", "1E-7", "123.4500",
             "21000000.00000000", "1E+100000", "-1.5E-300", "12345678901234567890123456789012345", "9.99E+6"]
    for text in texts:
        for kwargs in ({}, {"default": str}, {"default": str, "separators": COMPACT, "sort_keys": True}):
            vectors.dumps([Decimal(text)], kwargs)
    gen.decimals = True
    for _ in range(count(150)):
        vectors.dumps({"amount": gen.decimal(), "rate": gen.decimal()}, {"default": str, "sort_keys": True})


def layouts(vectors: Vectors, gen: Generator) -> None:
    docs = [[], {}, [[]], [{}], {"a": []}, {"a": {}}, [1, [2, [3, {"x": None}]]], {"a": [1, 2], "b": {"c": "d"}}]
    for _ in range(count(12)):
        docs.append(gen.document())
    variants = [
        {"indent": 0}, {"indent": 1}, {"indent": 4}, {"indent": "\t"}, {"indent": ""}, {"indent": "ab"},
        {"separators": (", ", ": ")}, {"separators": (",", ": ")}, {"separators": (" , ", " : ")},
        {"indent": "\t", "separators": (" , ", " : ")}, {"indent": 2, "separators": COMPACT},
    ]
    for doc in docs:
        for kwargs in variants:
            vectors.dumps(doc, kwargs)


def error_order(vectors: Vectors) -> None:
    nan, inf, lone = float("nan"), float("inf"), "\ud800"
    cases = [
        ([nan, Decimal(1)], {"allow_nan": False}),
        ([Decimal(1), nan], {"allow_nan": False}),
        ({"a": nan, 1: 2}, {"sort_keys": True, "allow_nan": False}),
        ([nan, {"a": 1, 1: 2}], {"sort_keys": True, "allow_nan": False}),
        ([lone, nan], {"ensure_ascii": False, "allow_nan": False}),
        ([lone, Decimal(1)], {"ensure_ascii": False}),
        ([lone, {"a": 1, 1: 2}], {"ensure_ascii": False, "sort_keys": True}),
        ([lone, 10**5000], {"ensure_ascii": False}),
        ([Decimal(1), 10**5000], {}),
        ([10**5000, Decimal(1)], {}),
        ({nan: 1}, {"allow_nan": False}),
        ({inf: 1, 1: 2}, {"allow_nan": False, "sort_keys": True}),
        ({"z": Decimal(1), "a": nan}, {"sort_keys": True, "allow_nan": False}),
        ({"z": Decimal(1), "a": nan}, {"allow_nan": False}),
    ]
    for obj, kwargs in cases:
        vectors.dumps(obj, kwargs)


def generate(seed: int) -> list[str]:
    rng = random.Random(seed)
    gen = Generator(rng)
    vectors = Vectors()
    floats(vectors, rng)
    strings(vectors)
    ints(vectors)
    specials(vectors)
    keys(vectors)
    decimals(vectors, gen)
    layouts(vectors, gen)
    error_order(vectors)
    for kwargs in SURVEYED:
        for _ in range(count(25)):
            gen.decimals = rng.random() < 0.3
            gen.nonfinite = rng.random() < 0.1
            gen.surrogates = False
            vectors.dumps(gen.kassiber_shape(), kwargs)
    for kwargs in GRID:
        for _ in range(count(45)):
            doc = gen.document()
            while kwargs.get("sort_keys") and nan_key_under_sort(doc):
                doc = gen.document()
            vectors.dumps(doc, kwargs)
    return vectors.lines


def main() -> None:
    global SCALE
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument("--scale", type=float, default=1.0, help="multiply the random case counts")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="where to write the vectors")
    args = parser.parse_args()
    if sys.version_info[:2] != (3, 11):
        raise SystemExit("generate the vectors with CPython 3.11, the version Kassiber ships")
    if sys.get_int_max_str_digits() != 4300:
        raise SystemExit("run with the default int_max_str_digits (4300)")
    SCALE = args.scale
    lines = generate(args.seed)
    text = HEADER.replace("@SEED@", str(args.seed)) + "\n".join(lines) + "\n"
    size = len(text.encode("ascii"))
    if args.output == OUTPUT and size >= MAX_BYTES:
        raise SystemExit(f"{size} bytes exceeds the {MAX_BYTES}-byte budget for the checked-in vectors")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="ascii")
    print(f"wrote {len(lines)} cases, {size} bytes to {args.output}")


if __name__ == "__main__":
    main()
