#!/usr/bin/env python3
"""Generate CPython json.dumps and float repr vectors for kassiber-pyjson.

The crate must write what CPython's json.dumps writes, byte for byte, for
every keyword combination Kassiber uses (crates/pyjson/README.md lists them;
scripts/survey_json_dumps.py finds them). This script computes the expected
text with the real json module and float.__repr__.

Run it with the repository virtualenv's CPython 3.11:

    .venv/bin/python crates/pyjson/scripts/gen_json_vectors.py

It writes crates/pyjson/tests/data/json_vectors.txt. The output depends only
on the fixed seed and the Python version recorded in its header, whose
comment documents the line format. For a stress run, write a larger set
elsewhere and point the Rust test at it:

    .venv/bin/python crates/pyjson/scripts/gen_json_vectors.py \\
        --seed 7 --scale 20 --output /tmp/json_stress.txt
    KASSIBER_JSON_VECTORS=/tmp/json_stress.txt \\
        cargo test -p kassiber-pyjson --test json_vectors
"""

