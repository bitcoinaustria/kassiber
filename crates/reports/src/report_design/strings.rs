#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    #[test]
    fn both_tables_carry_the_same_keys_once() {
        for table in [EN, DE] {
            let keys: BTreeSet<&str> = table.iter().map(|(k, _)| *k).collect();
            assert_eq!(keys.len(), table.len(), "duplicate key");
        }
        let en: BTreeSet<&str> = EN.iter().map(|(k, _)| *k).collect();
        let de: BTreeSet<&str> = DE.iter().map(|(k, _)| *k).collect();
        assert_eq!(
            en.symmetric_difference(&de).collect::<Vec<_>>(),
            Vec::<&&str>::new()
        );
        for (key, value) in EN.iter().chain(DE) {
            assert!(!value.trim().is_empty(), "{key}");
        }
    }
}
